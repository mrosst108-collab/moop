def run(programs=150, seed=5):
    results = []
    work = tempfile.mkdtemp(prefix='selvage-mutation-')
    try:
        for name, fname, old, new, part in MUTATIONS:
            copy = os.path.join(work, 'copy')
            shutil.rmtree(copy, ignore_errors=True)
            shutil.copytree(ROOT, copy, ignore=shutil.ignore_patterns('__pycache__', '*.pyc', '.pytest_cache'))
            path = os.path.join(copy, 'selvage', fname)
            with open(path) as f:
                text = f.read()
            if text.count(old) != 1:
                results.append((name, False, 'the mutation no longer applies'))
                continue
            with open(path, 'w') as f:
                f.write(text.replace(old, new))
            code = (f"import sys; sys.path.insert(0, {copy!r}); sys.path.insert(0, {os.path.join(copy, 'tests')!r})\n"
                    "import generated_04 as g\n"
                    f"part = dict(g.PARTS)[{part!r}]\n"
                    f"try:\n    stats, findings = part({programs}, {seed})\n"
                    "    print(len(findings), findings[0][0] if findings else '-')\n"
                    "except Exception as e:\n    print('crash:', type(e).__name__, str(e)[:70])\n")
            out = subprocess.run([sys.executable, '-c', code], capture_output=True, text=True, cwd=copy)
            seen = out.stdout.strip() or out.stderr.strip()[-120:]
            results.append((name, not seen.startswith('0 '), seen))
    finally:
        shutil.rmtree(work, ignore_errors=True)
    return results


if __name__ == '__main__':
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 150
    s = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    results = run(n, s)
    for name, noticed, seen in results:
        print(f'{"noticed" if noticed else "MISSED":<8} {name:<58} {seen[:80]}')
    missed = sum(1 for _, noticed, _ in results if not noticed)
    print(f'{len(results) - missed} of {len(results)} mutations noticed')
    sys.exit(1 if missed else 0)
